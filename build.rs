use cc ;

fn main() {
    // компилирует native/distance.c в distance.lib
    cc::Build::new()    // // 1. Создаёт новый экземпляр билдера для C-компилятора.
        .file("native/distance.c")  // 2. Добавляет файл который будет скомпилирован
        .compile("distance");  // Аргумент определяет иля файла для скомпилированной библиотеке.
}
